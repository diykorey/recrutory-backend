USE kandidato;
GO
CREATE TABLE USERS (
  USER_ID bigint  NOT NULL IDENTITY(1, 1) PRIMARY KEY,
  LOGIN varchar(100) NOT NULL UNIQUE,
  PASSWORD varbinary NOT NULL,
  FIRST_NAME varchar(100) NOT NULL,
  LAST_NAME varchar(100) NOT NULL
);

CREATE TABLE VACANCIES (
  VACANCY_ID bigint NOT NULL IDENTITY(1, 1) PRIMARY KEY,
  CREATION_TIME datetime NOT NULL,
  HOT_FLAG bit DEFAULT 1,
  DESCRIPTION varchar(4000) DEFAULT NULL,
  STATE varchar(20) NOT NULL,
  USER_ID bigint NOT NULL FOREIGN KEY REFERENCES USERS (USER_ID),
  NUMBER varchar(50) DEFAULT NULL,
  NAME varchar(100) DEFAULT NULL
);

CREATE TABLE CANDIDATES
(
  CANDIDATE_ID bigint NOT NULL IDENTITY(1, 1) PRIMARY KEY,
  FIRST_NAME varchar(50) NOT NULL,
  LAST_NAME varchar(50) NOT NULL,
  CREATION_TIME datetime NOT NULL,
  USER_ID bigint NOT NULL FOREIGN KEY REFERENCES USERS (USER_ID)
);

CREATE TABLE TAGS (
  TAG_ID bigint NOT NULL IDENTITY(1, 1) PRIMARY KEY,
  KEYWORD varchar(30) NOT NULL
);

CREATE TABLE CANDIDATE_TAGS
(
  TAG_ID bigint NOT NULL FOREIGN KEY REFERENCES TAGS (TAG_ID) ON DELETE CASCADE,
  CANDIDATE_ID bigint NOT NULL FOREIGN KEY REFERENCES CANDIDATES (CANDIDATE_ID) ON DELETE CASCADE
    PRIMARY KEY (TAG_ID, CANDIDATE_ID)
);

CREATE TABLE CONTACTS
(
  CONTACT_ID   bigint      NOT NULL IDENTITY(1, 1) PRIMARY KEY,
  CONTACT_TYPE varchar(30) NOT NULL,
  VALUE        varchar(30) NOT NULL,
  CANDIDATE_ID bigint      NOT NULL FOREIGN KEY REFERENCES CANDIDATES (CANDIDATE_ID) ON DELETE CASCADE
);

CREATE TABLE FLOWS (
  FLOW_ID bigint NOT NULL IDENTITY(1, 1) PRIMARY KEY,
  CREATION_TIME datetime NOT NULL,
  ACTIVE_FLAG bit DEFAULT 1,
  VACANCY_ID bigint NOT NULL FOREIGN KEY REFERENCES VACANCIES (VACANCY_ID) ON DELETE CASCADE,
  CANDIDATE_ID bigint NOT NULL FOREIGN KEY REFERENCES CANDIDATES (CANDIDATE_ID) ON DELETE CASCADE,
  USER_ID bigint NOT NULL FOREIGN KEY REFERENCES USERS (USER_ID),
);

CREATE TABLE FLOW_ACTIONS (
  FLOW_ACTION_ID bigint NOT NULL IDENTITY(1, 1) PRIMARY KEY,
  CREATION_TIME datetime NOT NULL,
  FLOW_ID bigint NOT NULL FOREIGN KEY REFERENCES FLOWS(FLOW_ID) ON DELETE CASCADE,
  DESCRIPTION varchar(4000) DEFAULT NULL,
  STATE varchar(20) NOT NULL
);

CREATE TABLE RESUME (
  RESUME_ID bigint NOT NULL IDENTITY(1, 1) PRIMARY KEY,
  DATA_URL varchar(50) NOT NULL,
  STATE varchar(20) NOT NULL,
  CANDIDATE_ID bigint NOT NULL FOREIGN KEY REFERENCES CANDIDATES (CANDIDATE_ID) ON DELETE CASCADE,
  USER_ID bigint NOT NULL FOREIGN KEY REFERENCES USERS (USER_ID)
);

CREATE TABLE VACANCIES_TAGS (
  TAG_ID bigint NOT NULL FOREIGN KEY (TAG_ID) REFERENCES TAGS (TAG_ID) ON DELETE CASCADE,
  VACANCY_ID bigint NOT NULL FOREIGN KEY (VACANCY_ID) REFERENCES VACANCIES (VACANCY_ID) ON DELETE CASCADE,
  PRIMARY KEY (TAG_ID, VACANCY_ID)
);

CREATE TABLE COMMENTS
(
  COMMENT_ID bigint NOT NULL IDENTITY(1, 1) PRIMARY KEY,
  ENTITY_ID bigint NOT NULL,
  USER_ID bigint NOT NULL FOREIGN KEY REFERENCES USERS (USER_ID),
  CREATION_DATE datetime NOT NULL,
  ENTITY_TYPE varchar(10) DEFAULT NULL,
  STATEMENT varchar(4000) DEFAULT NULL,
);


CREATE TABLE TIMELINE_RECORD (
  TIMELINE_RECORD_ID        	bigint NOT NULL IDENTITY(1, 1) PRIMARY KEY,
  CREATION_TIME 				datetime NOT NULL,
  CANDIDATE_ID     				bigint NOT NULL FOREIGN KEY REFERENCES CANDIDATES (CANDIDATE_ID),
  USER_ID     					bigint NOT NULL FOREIGN KEY REFERENCES USERS (USER_ID),
);

CREATE TABLE TIMELINE_FIELD_TYPE (
  TIMELINE_FIELD_TYPE_ID        bigint NOT NULL IDENTITY(1, 1) PRIMARY KEY,
  LABEL    				    	VARCHAR(512) NOT NULL,
  PRIME    						bit DEFAULT 0,
  COUNTERPART    				bit DEFAULT 0,
  USER_ID     					bigint NOT NULL FOREIGN KEY REFERENCES USERS (USER_ID)
);

CREATE TABLE TIMELINE_FIELD (
  TIMELINE_FIELD_ID             bigint NOT NULL IDENTITY(1, 1) PRIMARY KEY,
  FIELD_VALUE    				VARCHAR(512) NOT NULL,
  TIMELINE_FIELD_TYPE_ID     	bigint NOT NULL FOREIGN KEY REFERENCES TIMELINE_FIELD_TYPE (TIMELINE_FIELD_TYPE_ID),
  TIMELINE_RECORD_ID     		bigint NOT NULL FOREIGN KEY REFERENCES TIMELINE_RECORD (TIMELINE_RECORD_ID),
  USER_ID     					bigint NOT NULL FOREIGN KEY REFERENCES USERS (USER_ID)
);